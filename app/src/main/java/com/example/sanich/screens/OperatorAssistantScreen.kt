@Composable
fun OperatorAssistantScreen(onBack: () -> Unit) {
    var selected by remember { mutableStateOf<AssistantTopic?>(null) }

    BackHandler {
        if (selected != null) selected = null else onBack()
    }

    Scaffold { paddingValues ->
        Column(Modifier.fillMaxSize().background(Color(0xFFF6F6F6)).padding(paddingValues)) {
            CalculationTopBar(selected?.title ?: "Помощник оператора") {
                if (selected != null) selected = null else onBack()
            }
            Column(
                Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(14.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                if (selected == null) {
                    Text("Операторские ситуации", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold, modifier = Modifier.padding(top = 8.dp))
                    assistantTopics.forEach { topic ->
                        Card(
                            Modifier.fillMaxWidth().clickable { selected = topic },
                            shape = RoundedCornerShape(14.dp),
                            colors = CardDefaults.cardColors(containerColor = Color.White)
                        ) {
                            Text(topic.title, Modifier.padding(16.dp), fontWeight = FontWeight.Bold)
                        }
                    }
                } else {
                    Card(colors = CardDefaults.cardColors(containerColor = Color(0xFFFFF3CD))) {
                        Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(10.dp)) {
                            selected!!.steps.forEachIndexed { index, step ->
                                Text(if (selected!!.preserveFormatting) step else "${index + 1}. $step")
                            }
                        }
                    }
                }
            }
        }
    }
}
